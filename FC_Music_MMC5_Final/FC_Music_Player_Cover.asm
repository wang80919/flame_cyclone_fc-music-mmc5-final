;封面音乐切换
Cover_Music_Init
    PHA
    LDA #$0F
    STA $4015
    PLA
    JSR Set_Sound_Init_Port
    JSR Sound_Init
    RTS

;==================================================
;封面音乐播放
Cover_Music_Play
    JSR Set_Sound_Play_Port
    JSR Sound_Play
    RTS

;==================================================
;重置封面滚动
Reset_Cover_Scroll
    LDA #$00
    STA Scroll_V
    LDA #$88
    STA PPU_Ctrl_Buf
    
    LDA #COVER_RESET_ALBUM - 1
    JSR Cover_Album_Init
    LDA #COVER_RESET_TRACK - 1
    JSR Cover_Music_Init
    RTS
    
;==================================================
;更新滚动
Update_VScroll
    LDA PPU_Ctrl_Buf
    AND #$02
    BEQ .End
    INC Scroll_V
    LDA Scroll_V
    CMP #$F0
    BCC .End
    JSR Reset_Cover_Scroll
.End
    RTS

;==================================================
;闪烁文本
Blink_Text
    LDA Cover_Mode_Time
    CMP #$FF
    BNE .Show
    LDA PPU_Ctrl_Buf
    AND #$02
    BNE .End
    LDA Nmi_Time_Count
    AND #(1 << BLINK_TEXT_INTERVAL) - 1
    BNE .End
    LDA Nmi_Time_Count
    LDX #BLINK_TEXT_INTERVAL
    BEQ .Check
.Shift
    LSR A
    DEX
    BNE .Shift
.Check
    AND #$01
    BEQ .Show
.Clear
    LDA #BLINK_TEXT_INDEX - 1
    JSR Clear_Cover_Text
    RTS
.Show
    LDA #BLINK_TEXT_INDEX - 1
    JSR Write_Cover_Text
    RTS
.End
    RTS
 
