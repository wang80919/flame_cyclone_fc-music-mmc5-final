;==================================================
;封面处理
Cover_Process
    JSR Wait_Fot_Vblank
    JSR Init_Cover_Attributes
    
    ;JSR Init_Cover_Palette
    
    ;写入调色板数据
    LDA #25 - 1
    JSR Write_Cover_Text
    
    JSR Init_Cover_Text
    
    ;设置屏幕镜像($50: 水平; $44: 垂直)
    LDA #$50
    STA MAPPER_REG_NT_MAPPING
    
    LDA #$FF
    STA Cover_Mode_Time
    
    ;音乐bank初始化
    LDA #COVER_SCROLL_ALBUM - 1
    JSR Cover_Album_Init
    LDA #COVER_SCROLL_TRACK - 1
    JSR Cover_Music_Init
    
    LDA #$1E
    STA PPU_Mask_Buf
    LDA #$8A
    STA PPU_Ctrl_Buf
    STA PPU_CTRL
    
    JSR .Wait_Press_Start
    RTS

.Wait_Press_Start
    LDA Fast_Item
    AND Fast_Music
    CMP #$FF
    BNE .Quit
    
    LDA Cover_Mode_Time
    BNE .Wait_Press_Start
    
.Quit
    LDA #$00
    STA PPU_Ctrl_Buf
    STA PPU_Mask_Buf
    STA PPU_CTRL
    STA PPU_MASK
    STA PPU_Buf_Pos
    STA Cover_Mode_Time
    
    JSR Sound_Port_Clear
    JSR Vram_Clear
    
    LDA Fast_Item
    PHA
    LDA Fast_Music
    PHA
    JSR Init_Ex_Ram
    PLA
    STA Fast_Music
    PLA
    STA Fast_Item
    
    ;设置屏幕镜像($50: 水平; $44: 垂直)
    LDA #$44
    STA MAPPER_REG_NT_MAPPING

    JSR Sound_Ram_Clear_Part_1
    
.End
    RTS

;==================================================
;封面NMI处理
Nmi_For_Cover
    LDA #$00
    STA PPU_CTRL
    
    JSR FC_PPU_Buffer_Process
    
    LDA PPU_Ctrl_Buf
    STA PPU_CTRL
    
    JSR Blink_Text
    ;JSR Blink_QR_Code
    ;JSR Blink_Custom_Text
    JSR Update_VScroll
    JSR .Quit_Delay
    
    ;处理手柄输入
    JSR Joystick_Proc
    
    LDA Cover_Mode_Time
    CMP #$FF
    BNE .End
    
    LDA Key_Once
    BEQ .End
    LDA PPU_Ctrl_Buf
    AND #$02
    BNE .Reset_Scroll
    LDA Key_Once
    CMP #$10
    BEQ .Quit
    BNE .End

.Reset_Scroll
    JSR Reset_Cover_Scroll
    
.End
    JSR Cover_Music_Play
    INC Nmi_Time_Count
    RTS

.Quit
    LDA PPU_Ctrl_Buf
    AND #$02
    BNE .Reset_Scroll
    LDA #COVER_QUIT_TIME
    STA Cover_Mode_Time
    
    LDA #COVER_QUIT_ALBUM - 1
    JSR Cover_Album_Init
    LDA #COVER_QUIT_TRACK - 1
    JSR Cover_Music_Init
    
    RTS
.Quit_Delay
    LDA Cover_Mode_Time
    CMP #$FF
    BEQ .Quit_Delay_End
    LDA Cover_Mode_Time
    BEQ .Quit_Delay_End
    DEC Cover_Mode_Time
.Quit_Delay_End
    RTS

;==================================================
;封面音乐集切换
Cover_Album_Init
